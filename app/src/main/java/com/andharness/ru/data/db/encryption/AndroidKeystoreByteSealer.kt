package com.andharness.ru.data.db.encryption

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import com.andharness.ru.domain.security.ByteSealer
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * [ByteSealer] backed by a non-extractable AES-256-GCM key in the **Android Keystore**
 * (update.md idea #7). The key never leaves the device and is never written to disk, so the sealed
 * database passphrase is useless to anyone who copies the app's private files.
 *
 * Binary layout of a sealed blob:
 * ```
 * formatVersion (1 byte)
 * ivLength      (1 byte)
 * iv            (ivLength bytes, random per seal)
 * ciphertext    (GCM ciphertext + 16-byte authentication tag)
 * ```
 * A fresh random IV is generated by the provider for every [seal], so sealing the same passphrase
 * twice yields different bytes. GCM authenticates the blob, so a tampered or foreign blob fails
 * [unseal] instead of yielding garbage bytes.
 *
 * Official references:
 * - Android Keystore — https://developer.android.com/privacy-and-security/keystore
 * - `KeyGenParameterSpec` — https://developer.android.com/reference/android/security/keystore/KeyGenParameterSpec
 * - `Cipher` — https://developer.android.com/reference/javax/crypto/Cipher
 */
class AndroidKeystoreByteSealer : ByteSealer {

    override fun seal(plaintext: ByteArray): ByteArray {
        // The IV is generated by the provider, not supplied by us: a Keystore AES-GCM key is created
        // with randomized encryption required (the default) and rejects a caller-provided IV with
        // "Caller-provided IV not permitted". Cipher.getIV() returns the IV the provider used.
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, loadOrCreateKey())
        val iv = cipher.iv
        require(iv.size in 1..MAX_IV_LENGTH) { "Неожиданная длина IV: ${iv.size}" }
        val body = cipher.doFinal(plaintext)
        return ByteArray(HEADER_BYTES + iv.size + body.size).also { out ->
            out[0] = FORMAT_VERSION
            out[1] = iv.size.toByte()
            System.arraycopy(iv, 0, out, HEADER_BYTES, iv.size)
            System.arraycopy(body, 0, out, HEADER_BYTES + iv.size, body.size)
        }
    }

    override fun unseal(sealed: ByteArray): ByteArray {
        require(sealed.size > HEADER_BYTES) { "Слишком короткий зашифрованный блок." }
        require(sealed[0] == FORMAT_VERSION) {
            "Неподдерживаемая версия зашифрованного блока: ${sealed[0]}."
        }
        val ivLength = sealed[1].toInt() and 0xFF
        require(ivLength in 1..MAX_IV_LENGTH) { "Повреждённый зашифрованный блок: неверная длина IV." }
        require(sealed.size > HEADER_BYTES + ivLength) { "Повреждённый зашифрованный блок." }

        val iv = sealed.copyOfRange(HEADER_BYTES, HEADER_BYTES + ivLength)
        val body = sealed.copyOfRange(HEADER_BYTES + ivLength, sealed.size)
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, loadOrCreateKey(), GCMParameterSpec(TAG_BITS, iv))
        return cipher.doFinal(body)
    }

    private fun loadOrCreateKey(): SecretKey {
        val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
        (keyStore.getEntry(KEY_ALIAS, null) as? KeyStore.SecretKeyEntry)?.secretKey?.let { return it }

        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        generator.init(
            KeyGenParameterSpec.Builder(
                KEY_ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(KEY_SIZE_BITS)
                // No user-authentication requirement: background workers must be able to open the
                // database without the screen being unlocked. The key is still device-bound.
                .build()
        )
        return generator.generateKey()
    }

    private companion object {
        const val ANDROID_KEYSTORE = "AndroidKeyStore"
        const val KEY_ALIAS = "andharness_db_passphrase_key"
        const val KEY_SIZE_BITS = 256
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val TAG_BITS = 128
        const val HEADER_BYTES = 2
        const val MAX_IV_LENGTH = 32
        const val FORMAT_VERSION: Byte = 1
    }
}
