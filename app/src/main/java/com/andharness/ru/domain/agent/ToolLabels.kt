    /** Returns a short human-readable Russian label for [tool]. Unknown names degrade gracefully. */
    fun label(tool: String): String {
        val key = tool.trim()
        if (key.isEmpty()) return "Действие: неизвестно"
        return LABELS[key] ?: fallback(key)
    }

    /**
     * Readable label derived from the name itself. Dynamic MCP tools
     * (`mcp_<server>_<tool>`, see `McpServerRules.qualifiedToolName`) get an explicit `MCP:` prefix so
     * a remote call is never mistaken for a built-in action; anything else keeps the neutral
     * «Действие: …» wording (never the raw snake_case).
     */
    private fun fallback(key: String): String {
        if (key.startsWith(MCP_PREFIX)) {
            val readable = key.removePrefix(MCP_PREFIX).replace('_', ' ').trim()
            return if (readable.isEmpty()) "MCP" else "MCP: $readable"
        }
        return "Действие: ${key.replace('_', ' ')}"
    }

    /** Must stay in sync with `McpDynamicTools.PREFIX` (no dependency from domain.agent → domain.mcp). */
    private const val MCP_PREFIX = "mcp_"
