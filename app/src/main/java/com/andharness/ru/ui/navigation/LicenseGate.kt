package com.andharness.ru.ui.navigation

/**
 * Единая точка решения первого экрана приложения: выбор языка → лицензионный гейт (EULA) →
 * настройка модели (онбординг) → главный экран (чаты).
 *
 * Выделено в чистый объект без Android-зависимостей, чтобы порядок первого запуска был одним
 * тестируемым местом, а не размазанным по нескольким вызовам.
 *
 * Гейт завершения первого запуска — СОХРАНЁННОЕ подключение к модели (провайдер/эндпоинт; см.
 * `LlmSettingsStore.isConfigured()`). Пока подключение не сохранено, приложение на КАЖДОМ запуске
 * начинает поток заново с выбора языка: он НЕ возобновляется с середины и НЕ пропускает экран языка,
 * даже если язык выбирали ранее. После сохранения подключения первый экран — главный (чаты), и
 * онбординг больше не показывается (язык меняется только в «Настройках»).
 *
 * Поведение при неподтверждённой лицензии — DROP (отбрасываем), а не HOLD (откладываем):
 * входящее намерение/deep link не обрабатывается и не повторяется после принятия; после принятия
 * пользователь продолжает обычный поток (онбординг → главный экран).
 *
 * Официальная документация: Navigation deep links —
 * https://developer.android.com/develop/ui/compose/navigation#deeplinks
 * Обработка новых намерений в уже запущенной Activity —
 * https://developer.android.com/reference/android/app/Activity#onNewIntent(android.content.Intent)
 */
object LicenseGate {

    /**
     * Стартовый экран. Гейт — сохранённое подключение к модели: пока его нет, поток всегда
     * начинается с выбора языка ([AppDestination.LANGUAGE]) — экран не пропускается из-за того, что
     * язык уже выбирали; как только подключение сохранено — главный экран, список чатов
     * ([AppDestination.CHATS]).
     */
    fun startDestination(modelConfigured: Boolean): String =
        if (modelConfigured) AppDestination.CHATS else AppDestination.LANGUAGE

    /**
     * Куда идти после явного выбора языка: на лицензию, если она ещё не принята, иначе сразу на
     * онбординг (настройка модели). Нужно, чтобы обновление уже принявшего лицензию пользователя не
     * показывало ему EULA повторно.
     */
    fun afterLanguage(licenseAccepted: Boolean): String =
        if (licenseAccepted) AppDestination.ONBOARDING else AppDestination.LICENSE

    /**
     * Разрешено ли обрабатывать входящее намерение (deep link уведомления, share, process text,
     * плитка быстрых настроек, виджет). `false` означает: навигация за пределы лицензионного гейта
     * запрещена.
     */
    fun inboundAllowed(licenseAccepted: Boolean): Boolean = licenseAccepted
}
